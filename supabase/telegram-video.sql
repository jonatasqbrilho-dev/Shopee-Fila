alter table produtos add column if not exists video_fonte text;
alter table produtos add column if not exists video_telegram_channel text;
alter table produtos add column if not exists video_telegram_message_id text;
alter table produtos add column if not exists video_match_score numeric;
alter table produtos add column if not exists video_match_status text;

create table if not exists telegram_video_catalog (
  id bigint generated by default as identity primary key,
  telegram_channel text not null,
  telegram_message_id bigint not null,
  telegram_message_url text,
  telegram_caption text,
  thumbnail_url text,
  video_url text,
  match_score numeric default 0,
  match_reason text,
  selecionado_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (telegram_channel, telegram_message_id)
);

create index if not exists telegram_video_catalog_score on telegram_video_catalog (match_score desc);
create index if not exists telegram_video_catalog_channel on telegram_video_catalog (telegram_channel, telegram_message_id desc);
alter table telegram_video_catalog enable row level security;
